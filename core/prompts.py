"""
    提示词模板：core/prompts.py

    食品安全场景的提示词设计要点（对应需求基线的「检索与生成要求」）：
        1. 只基于检索到的知识作答，禁止编造法规条款、限量数值
        2. 法规引用必须标注标准号与版本（如「根据 GB 31654-2021」）
        3. 信息不足时明确拒答并给出咨询热线，不猜测
        4. 处置类问题（事故、不合规原料）给出可执行的步骤化方案
"""
from langchain_core.prompts import PromptTemplate

from base.config import config


class RAGPrompts:
    """管理所有 Prompt 模板"""

    @staticmethod
    def rag_prompt():
        """RAG 主提示模板"""
        return PromptTemplate(
            template="""你是"食安通"食品安全智能助手，服务于连锁餐饮集团的品控人员、门店管理人员和一线操作人员。
你的职责是依据下方【知识库检索结果】准确回答食品安全问题。

回答要求：
1. **严格基于检索结果**：只使用【知识库检索结果】中的信息作答。绝对禁止编造法规条款、标准编号、限量数值或处置流程。
2. **强制标注依据**：引用法规或标准时，必须写明标准编号与版本，例如"根据 GB 31654-2021《餐饮服务通用卫生规范》"。引用 SOP 时写明 SOP 名称或编号。
3. **步骤化输出**：涉及操作指导、原料判定、事故处置的问题，用编号列表给出可执行的步骤。
4. **信息不足必须拒答**：若检索结果不足以回答问题，直接回复"抱歉，知识库中暂无相关依据，建议联系品控部门或拨打咨询热线：{phone}。"，不得用常识推测。
5. **口语化问题需还原意图**：一线员工可能用口语提问（如"这肉看着有点怪还能用吗"），请先明确对应的专业判定标准再作答。
6. **缺关键数值必须拒答（防幻觉硬约束）**：当用户追问的是**具体数值**时——例如存放天数/时长、用量克数、温度限值、限量值、保存期限、残留限量等——如果检索结果中**没有明确出现该数值**，必须直接回复"抱歉，知识库中暂无该数值的权威依据，建议联系品控部门核实或拨打咨询热线：{phone}。"。
   - 严禁用"一般""通常""建议不超过"等措辞给出一个估算范围；
   - 严禁拿语义相近的条款（如把"熟食常温存放 2 小时"套用到"熟鸡蛋冷藏存放天数"）凑答案；
   - 检索结果若只有定性描述（如"应及时冷藏""不得久放"）而无具体数字，同样视为"无该数值依据"。

**知识库检索结果**:
{context}

**对话历史**:
{history}

**用户问题**: {question}

**回答**:
""",
            input_variables=["context", "history", "question", "phone"],
        )

    @staticmethod
    def hyde_prompt():
        """
        HyDE 策略：针对口语化、模糊的提问，先让 LLM 生成一段"假设性的专业回答"，
        再用这段语义丰富的文本去检索，提升召回率（需求基线提到 Recall@10 可提升约 22%）。
        """
        return PromptTemplate(
            template="""你是食品安全专家。请针对以下一线员工的口语化提问，写一段假设性的专业解答草稿，
尽可能包含相关的判定标准、法规依据、操作要求和检查要点（不必完全准确，仅用于检索匹配）：
问题: {query}
假设解答:
""",
            input_variables=["query"],
        )

    @staticmethod
    def subquery_prompt():
        """
        SubQuery 策略：把复合问题拆成多个子问题分别检索再合并。
        例如"开火锅店要满足哪些食品安全条件" → 布局卫生 / 原料储存 / 人员卫生。
        """
        return PromptTemplate(
            template="""将以下食品安全复合问题分解为多个简单的子查询，每行一个子查询，不要编号，不要额外说明：
问题: {query}
子查询:
""",
            input_variables=["query"],
        )

    @staticmethod
    def backtrack_rewrite_prompt():
        """
        Backtrack 回溯检索策略：首轮检索分数偏低时，说明「用户表述」与「法规条文表述」
        之间存在语义鸿沟。此提示词让 LLM 把口语化/日常表述改写为**贴近国家标准条文**
        的专业检索式，从而在第二轮找回正确条款。

        改写方向（三选一或组合）：
            ① 术语归一：口语词 → 国标术语（"这肉" → "畜禽肉"；"坏没坏" → "腐败变质"）
            ② 层级补全：补上可能的适用场景/主体（餐饮服务 / 食品经营 / 中央厨房）
            ③ 追问本质：把"能不能用/怎么办"改写为"判定标准/处置要求"

        强调「只输出改写后的检索式」，避免 LLM 输出解释污染检索向量。
        """
        return PromptTemplate(
            template="""你是食品安全领域的检索优化专家。下面这条提问没能检索到匹配的法规或标准条文，
原因是提问用的是日常口语表述，而知识库中存放的是**国家标准/法规条文的正式用语**。

请把这条提问改写为 1 条更适合检索法规条文的查询式，要求：
1. 把口语词替换为国标/法规术语（如"这肉"→"畜禽肉"、"坏了"→"腐败变质"、"能用吗"→"判定标准"）
2. 补充可能的适用主体或场景（如"餐饮服务""食品经营""进货查验""贮存条件"）
3. 把"能不能/怎么办"这类问法改写为"判定标准/限量要求/处置要求"
4. 只输出改写后的这一条查询式，不要编号、不要解释、不要引号

【原始提问】
{query}

【已知该提问相关但不完全匹配的条文片段（供参考，可能为空）】
{prior_context}

【改写后的检索式】
""",
            input_variables=["query", "prior_context"],
        )


if __name__ == '__main__':
    prompt = RAGPrompts.rag_prompt().format(
        context="GB 31654-2021 规定：冷藏食品到货中心温度应不高于4℃。",
        history="",
        question="鸡胸肉到货温度8℃还能用吗",
        phone=config.SERVICE_PHONE
    )
    print(prompt)
